#!/usr/bin/env python3
"""
场景人工审核工具。

使用 rich 库提供交互式 CLI，逐个展示场景内容并收集审核意见。

用法:
    # 审核单个场景
    python review_tool.py --scenario ../data/scenarios/onboard_01.json

    # 审核目录中所有未审核的场景
    python review_tool.py --scenario-dir ../data/scenarios/
"""

import argparse
import json
import logging
import sys
from pathlib import Path
from typing import List, Optional

from rich.console import Console
from rich.panel import Panel
from rich.prompt import Prompt
from rich.table import Table

try:
    from .models import Scenario, ScenarioValidator
except ImportError:  # pragma: no cover - keeps direct script execution working
    from models import Scenario, ScenarioValidator

logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
logger = logging.getLogger(__name__)

console = Console()


def load_scenario(path: Path) -> Optional[Scenario]:
    """加载单个场景文件。"""
    try:
        with open(path, "r", encoding="utf-8") as f:
            data = json.load(f)
        return Scenario.from_dict(data)
    except (json.JSONDecodeError, KeyError, TypeError) as e:
        logger.error(f"无法加载 {path.name}: {e}")
        return None


def save_scenario(scenario: Scenario, path: Path) -> None:
    """将场景保存回原始 JSON 文件。"""
    with open(path, "w", encoding="utf-8") as f:
        json.dump(scenario.to_dict(), f, ensure_ascii=False, indent=2)


def collect_scenario_paths(scenario_dir: Path, skip_approved: bool = True) -> List[Path]:
    """收集目录中需要审核的场景文件路径。"""
    paths: List[Path] = []

    for path in sorted(scenario_dir.glob("*.json")):
        if not skip_approved:
            paths.append(path)
            continue

        # 快速检查是否已审核通过，无需完整解析
        try:
            with open(path, "r", encoding="utf-8") as f:
                data = json.load(f)
            metadata = data.get("metadata", {})
            if metadata.get("review_status") == "approved":
                continue
        except (json.JSONDecodeError, KeyError):
            pass  # 无法解析的文件仍然列入队列

        paths.append(path)

    return paths


def display_scenario(scenario: Scenario) -> None:
    """展示场景的完整内容。"""
    # -- 概览面板 --
    review_label = scenario.metadata.review_status or "unreviewed"
    overview_text = (
        f"[bold]ID:[/bold] {scenario.scenario_id}\n"
        f"[bold]Domain:[/bold] {scenario.domain}\n"
        f"[bold]Description:[/bold] {scenario.description}\n"
        f"[bold]Seed:[/bold] {scenario.metadata.seed_id}  "
        f"[bold]Variant:[/bold] {scenario.metadata.variant or 'seed'}\n"
        f"[bold]Generated by:[/bold] {scenario.metadata.generated_by}  "
        f"[bold]Review:[/bold] {review_label}"
    )
    console.print(Panel(overview_text, title="Scenario Overview", border_style="blue"))

    # -- 用户画像 --
    profile_text = (
        f"[bold]Persona:[/bold] {scenario.user_profile.persona}\n"
        f"[bold]Context:[/bold] {scenario.user_profile.context}\n"
        f"[bold]Style:[/bold] {scenario.user_profile.communication_style}"
    )
    console.print(Panel(profile_text, title="User Profile", border_style="cyan"))

    # -- 事实表 --
    fact_table = Table(title="Fact Sheet", show_lines=True)
    fact_table.add_column("ID", style="bold", width=6)
    fact_table.add_column("Category", width=12)
    fact_table.add_column("Fact")

    for fact in scenario.fact_sheet:
        fact_table.add_row(fact.id, fact.category, fact.fact)

    console.print(fact_table)

    # -- 用户需求 --
    need_table = Table(title="User Needs", show_lines=True)
    need_table.add_column("ID", style="bold", width=6)
    need_table.add_column("Order", width=6, justify="center")
    need_table.add_column("Level", width=12)
    need_table.add_column("Description")
    need_table.add_column("Key Facts", width=14)
    need_table.add_column("Predictable After", width=18)
    need_table.add_column("Prediction Reason")

    for need in scenario.user_needs:
        # 高亮有 predictable_after 的行
        if need.predictable_after is not None:
            pred_cell = f"[bold green]{need.predictable_after}[/bold green]"
            reason_cell = need.prediction_reason or ""
        else:
            pred_cell = "[dim]--[/dim]"
            reason_cell = "[dim]--[/dim]"

        need_table.add_row(
            need.id,
            str(need.turn_order),
            need.level,
            need.description,
            ", ".join(need.key_fact_ids),
            pred_cell,
            reason_cell,
        )

    console.print(need_table)

    # -- 结构校验 --
    validator = ScenarioValidator()
    issues = validator.validate(scenario)
    if issues:
        issue_text = "\n".join(f"  [red]- {issue}[/red]" for issue in issues)
        console.print(
            Panel(issue_text, title="Structural Issues", border_style="red")
        )
    else:
        console.print(
            Panel("[green]No structural issues found.[/green]",
                  title="Structural Validation", border_style="green")
        )


def prompt_review_action() -> str:
    """提示用户选择审核动作，返回动作标识。"""
    console.print()
    console.print("[bold]Actions:[/bold]")
    console.print("  [green][a]pprove[/green]  - Mark as approved")
    console.print("  [yellow][r]evision needed[/yellow]  - Mark as needs-revision")
    console.print("  [dim][s]kip[/dim]  - Skip to next scenario")
    console.print("  [red][q]uit[/red]  - Exit review")
    console.print()

    while True:
        choice = Prompt.ask(
            "Your action",
            choices=["a", "r", "s", "q"],
            default="s",
        )
        return choice


def review_single(scenario: Scenario, file_path: Path) -> str:
    """
    展示并审核单个场景。

    Returns:
        执行的动作: "approved", "needs-revision", "skipped", "quit"
    """
    console.rule(f"[bold]{scenario.scenario_id}[/bold]")
    display_scenario(scenario)

    action = prompt_review_action()

    if action == "a":
        scenario.metadata.reviewed = True
        scenario.metadata.review_status = "approved"
        save_scenario(scenario, file_path)
        console.print(f"[green]Approved and saved: {file_path.name}[/green]")
        return "approved"

    if action == "r":
        scenario.metadata.review_status = "needs-revision"
        save_scenario(scenario, file_path)
        console.print(f"[yellow]Marked as needs-revision: {file_path.name}[/yellow]")
        return "needs-revision"

    if action == "q":
        return "quit"

    # "s" or anything else
    console.print("[dim]Skipped.[/dim]")
    return "skipped"


def review_directory(scenario_dir: Path) -> None:
    """审核目录中所有未审核通过的场景。"""
    paths = collect_scenario_paths(scenario_dir, skip_approved=True)
    total = len(list(scenario_dir.glob("*.json")))

    if not paths:
        console.print(f"[green]All {total} scenario(s) in {scenario_dir} are already approved.[/green]")
        return

    console.print(
        f"[bold]Found {len(paths)} scenario(s) to review "
        f"(out of {total} total).[/bold]"
    )
    console.print()

    reviewed_count = 0
    for idx, path in enumerate(paths, start=1):
        console.print(f"[dim]--- Progress: {idx}/{len(paths)} ---[/dim]")

        scenario = load_scenario(path)
        if scenario is None:
            console.print(f"[red]Skipping unloadable file: {path.name}[/red]")
            continue

        result = review_single(scenario, path)
        if result in ("approved", "needs-revision"):
            reviewed_count += 1

        if result == "quit":
            console.print(f"\n[bold]Exited early. Reviewed {reviewed_count} scenario(s) this session.[/bold]")
            return

        console.print()

    console.print(f"\n[bold]Review complete. Reviewed {reviewed_count}/{len(paths)} scenario(s).[/bold]")


def review_single_file(scenario_path: Path) -> None:
    """审核单个场景文件。"""
    scenario = load_scenario(scenario_path)
    if scenario is None:
        console.print(f"[red]Failed to load scenario: {scenario_path}[/red]")
        sys.exit(1)

    review_single(scenario, scenario_path)


def main():
    parser = argparse.ArgumentParser(description="交互式场景审核工具")
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument(
        "--scenario", type=Path,
        help="审核单个场景 JSON 文件",
    )
    group.add_argument(
        "--scenario-dir", type=Path,
        help="审核目录中所有未审核的场景",
    )
    args = parser.parse_args()

    if args.scenario:
        if not args.scenario.exists():
            console.print(f"[red]文件不存在: {args.scenario}[/red]")
            sys.exit(1)
        review_single_file(args.scenario)
    else:
        if not args.scenario_dir.exists():
            console.print(f"[red]目录不存在: {args.scenario_dir}[/red]")
            sys.exit(1)
        review_directory(args.scenario_dir)


if __name__ == "__main__":
    main()
